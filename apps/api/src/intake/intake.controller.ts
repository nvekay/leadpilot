import { Body, Controller, ForbiddenException, Get, HttpCode, NotFoundException, Post, Query } from '@nestjs/common';
import { randomUUID } from 'node:crypto';
import { z } from 'zod';
import { safeEqual } from '../common/internal-key.guard.js';
import { Public } from '../common/public.decorator.js';
import { parse } from '../common/zod.js';
import { env } from '../config/env.js';
import { LeadsService } from '../leads/leads.service.js';
import { PipelineQueue } from '../pipeline/pipeline.queue.js';
import { DEMO_MESSAGES } from './demo-messages.js';

const formSchema = z.object({
  // Generated by the form when it loads, so a double submit is one lead
  submissionId: z.uuid(),
  name: z.string().trim().min(1).max(200),
  email: z.email().max(320),
  company: z.string().trim().max(200).optional(),
  message: z.string().trim().min(10).max(10_000),
});

/** The fields of Postmark's inbound webhook that we use */
const postmarkSchema = z.object({
  MessageID: z.string().min(1),
  FromFull: z.object({ Email: z.email(), Name: z.string().optional() }),
  Subject: z.string().optional(),
  TextBody: z.string().optional(),
  StrippedTextReply: z.string().optional(),
});

@Controller('intake')
export class IntakeController {
  constructor(
    private readonly leads: LeadsService,
    private readonly queue: PipelineQueue,
  ) {}

  /** Website contact form, posted by the web app's server */
  @Post('form')
  async form(@Body() body: unknown) {
    const f = parse(formSchema, body);
    const message = f.company ? `Company: ${f.company}\n\n${f.message}` : f.message;
    return this.accept({
      source: 'form',
      externalId: f.submissionId,
      fromEmail: f.email,
      fromName: f.name,
      subject: 'Website contact form',
      body: message,
    });
  }

  /** Inbound email webhook (Postmark format), authenticated by a secret token in the URL */
  @Public()
  @Post('email')
  @HttpCode(200)
  async email(@Query('token') token: string | undefined, @Body() body: unknown) {
    const expected = env().INBOUND_WEBHOOK_TOKEN;
    if (!expected || !token || !safeEqual(token, expected)) throw new ForbiddenException();
    const m = parse(postmarkSchema, body);
    const text = (m.StrippedTextReply || m.TextBody || '').trim();
    return this.accept({
      source: 'email',
      externalId: m.MessageID,
      fromEmail: m.FromFull.Email,
      fromName: m.FromFull.Name || null,
      subject: m.Subject || null,
      body: text || '(empty message)',
    });
  }

  /** The sample emails a visitor can send on the demo page */
  @Get('demo')
  samples() {
    return DEMO_MESSAGES.map(({ id, label, fromName, fromEmail, subject, body }) => ({
      id,
      label,
      fromName,
      fromEmail,
      subject,
      preview: body.replace(/\s+/g, ' ').slice(0, 160),
    }));
  }

  /** Sends one of the sample emails into the pipeline, for the public demo */
  @Post('demo')
  async demo(@Body() body: unknown) {
    const { sampleId } = parse(z.object({ sampleId: z.string() }), body);
    const sample = DEMO_MESSAGES.find((m) => m.id === sampleId);
    if (!sample) throw new NotFoundException('Unknown sample');
    return this.accept({
      source: 'demo',
      // Every click is a new lead, so visitors can send the same sample again
      externalId: `${sample.id}-${randomUUID()}`,
      fromEmail: sample.fromEmail,
      fromName: sample.fromName,
      subject: sample.subject,
      body: sample.body,
    });
  }

  private async accept(input: Parameters<LeadsService['ingest']>[0]) {
    const { lead, duplicate } = await this.leads.ingest(input);
    // A redelivered message whose first enqueue failed (Redis down) gets queued now; the job id prevents doubles
    if (!duplicate || lead.status === 'received') await this.queue.enqueue('analyze', lead.id);
    return { id: lead.id, duplicate };
  }
}
